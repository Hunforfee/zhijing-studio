import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {createServer} from './server.mjs';
const require=createRequire('C:/Users/Hunfo/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json');
const {chromium}=require('playwright');
const outputDir=await mkdtemp(path.join(os.tmpdir(),'zhijing-minimax-ui-'));
let stored={apiKey:'synthetic-zhipu-key'};
const server=createServer({outputDir,service:{provider:'compatible',baseUrl:'https://fixture.test/v1',model:'fixture',apiKey:''},videoOptions:{loadConfig:async()=>stored,saveConfig:async c=>{stored=c;},checkComposer:async()=>true},fetchImpl:async()=>{throw Error('No external requests in UI checks');}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/*',route=>route.request().url().startsWith(origin)?route.continue():route.abort());
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.locator('#videoConfigure').click();
  await page.locator('#videoProvider').selectOption('minimax');
  assert.equal(await page.locator('#videoApiKey').inputValue(),'');
  assert.equal(await page.locator('#videoApiKey').getAttribute('required'),'');
  await page.locator('#videoModel').selectOption('MiniMax-Hailuo-2.3-Fast');
  await page.locator('#videoApiKey').fill('synthetic-minimax-key');
  await page.locator('#videoConfigForm [type=submit]').click();
  await page.waitForFunction(()=>!document.getElementById('videoConfigDialog').open);
  assert.match(await page.locator('#videoServiceStatus').textContent(),/MiniMax/);
  assert.equal(await page.locator('#videoAudio').isDisabled(),true);
  assert.equal(stored.profiles.minimax.model,'MiniMax-Hailuo-2.3-Fast');
  await page.locator('#videoConfigure').click();
  assert.equal(await page.locator('#videoModel').inputValue(),'MiniMax-Hailuo-2.3-Fast');
  assert.equal(await page.locator('#videoApiKey').inputValue(),'');
  assert.equal(await page.locator('#videoApiKey').getAttribute('required'),null);
  await page.locator('#videoProvider').selectOption('zhipu');
  assert.equal(await page.locator('#videoModel').isVisible(),false);
  await page.locator('#videoConfigForm [type=submit]').click();
  await page.waitForFunction(()=>!document.getElementById('videoConfigDialog').open);
  assert.equal(await page.locator('#videoAudio').isDisabled(),false);
  assert.equal(stored.profiles.zhipu.apiKey,'synthetic-zhipu-key');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#videoConfigure').click();
  await page.locator('#videoProvider').selectOption('minimax');
  const bounds=await page.locator('#videoConfigDialog').boundingBox();
  assert.ok(bounds.x>=0&&bounds.x+bounds.width<=391);
  const style=await page.locator('#videoProvider').evaluate(element=>({height:element.getBoundingClientRect().height,radius:getComputedStyle(element).borderRadius}));
  assert.equal(style.height,42);assert.equal(style.radius,'8px');
  await page.screenshot({path:'output/minimax-video-settings-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log('MiniMax video settings verified: provider/model selection, independent keys, audio capability, restored configuration and mobile layout. No paid calls.');
}finally{
  await browser.close();server.closeAllConnections();await new Promise(r=>server.close(r));
  assert.ok(path.resolve(outputDir).startsWith(path.resolve(os.tmpdir())+path.sep+'zhijing-minimax-ui-'));await rm(outputDir,{recursive:true,force:true});
}
